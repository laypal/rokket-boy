/** The pieces that actually draw: one id per slot (highest tier), in the
 *  fixed application order head → body → hands. Ignores anything without
 *  both an ITEMS wear def and GEAR_WEAR rows. */
export function wornGear(ownedIds: string[]): string[] {
  const best: Partial<Record<'head' | 'hands' | 'body', string>> = {};
  for (const id of new Set(ownedIds)) {
    const w = ITEMS[id]?.wear;
    if (!w || !GEAR_WEAR[id]) continue;
    const cur = best[w.slot];
    if (!cur || ITEMS[cur].wear!.tier < w.tier) best[w.slot] = id;
  }
  return (['head', 'body', 'hands'] as const).flatMap((s) => (best[s] ? [best[s]!] : []));
}

/** Compose worn gear into a charset. No worn gear → the base object BY
 *  REFERENCE, so decode's per-_id cache sees nothing new. */
export function composeCharset(base: Charset, ownedIds: string[]): Charset {
  const worn = wornGear(ownedIds);
  if (worn.length === 0) return base;
  let head = base.head;
  let body = base.body;
  for (const id of worn) {
    const g = GEAR_WEAR[id];
    if (g.slot === 'head') {
      head = { d: overlayRows(head.d, g.rows.d), u: overlayRows(head.u, g.rows.u), s: overlayRows(head.s, g.rows.s) };
    } else {
      body = {
        d0: overlayRows(body.d0, g.rows.d0), d1: overlayRows(body.d1, g.rows.d1),
        u0: overlayRows(body.u0, g.rows.u0), u1: overlayRows(body.u1, g.rows.u1),
        s0: overlayRows(body.s0, g.rows.s0), s1: overlayRows(body.s1, g.rows.s1),
      };
    }
  }
  return { head, body, pal: base.pal };
}
